const catalogs: Record<Locale, Catalog> = { ar, fr, en };

export function translate(locale: Locale, key: MessageKey, vars?: Vars) {
  const source = catalogs[locale][key] ?? catalogs.ar[key];
  if (!vars) return source;
  return source.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

function translateFrom(source: Catalog, key: MessageKey, vars?: Vars) {
  const raw = source[key] ?? ar[key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

/** Stable strings for matching message text (e.g. signal prefix) without subscribing to the store. */
const SIGNAL_PREFIXES: readonly string[] = Object.freeze([
  translateFrom(ar, 'signal.prefix'),
  translateFrom(fr, 'signal.prefix'),
  translateFrom(en, 'signal.prefix'),
]);

export function isSignalMessageText(text: string) {
  const head = text.trimStart();
  return SIGNAL_PREFIXES.some((prefix) => head.startsWith(prefix));
}

export function currentLocale(): Locale {
  return useSettingsStore.getState().locale;
}

export function dateLocale(locale: Locale = currentLocale()) {
  return locale === 'ar' ? 'ar' : locale;
}

export function t(key: MessageKey, vars?: Vars) {
  return translate(currentLocale(), key, vars);
}

export function useI18n() {
  const locale = useSettingsStore((state) => state.locale);
  const setLocale = useSettingsStore((state) => state.setLocale);
  return {
    locale,
    dir: locale === 'ar' ? 'rtl' as const : 'ltr' as const,
    setLocale,
    t: (key: MessageKey, vars?: Vars) => translate(locale, key, vars),
  };
}

export function syncLocale(locale: Locale) {
  applyLocale(locale);
}
